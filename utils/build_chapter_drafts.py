def callout(d, label, text):
    t=d.add_table(rows=1, cols=1); t.alignment=WD_TABLE_ALIGNMENT.CENTER
    c=t.cell(0,0); shade(c, LIGHT); set_cell_margins(c,120,160,120,160)
    p=c.paragraphs[0]; r=p.add_run(label+"："); r.bold=True; r.font.color.rgb=RGBColor.from_string(DARK)
    p.add_run(text)


def table(d, headers, rows, widths=None, font=8.5):
    t=d.add_table(rows=1, cols=len(headers)); t.alignment=WD_TABLE_ALIGNMENT.CENTER
    t.style="Table Grid"; t.autofit=False
    hdr=t.rows[0]; set_repeat_table_header(hdr)
    for i,h in enumerate(headers):
        hdr.cells[i].text=str(h); shade(hdr.cells[i], BLUE)
        for r in hdr.cells[i].paragraphs[0].runs: r.font.bold=True; r.font.color.rgb=RGBColor(255,255,255); r.font.size=Pt(font)
    for row in rows:
        cells=t.add_row().cells
        for i,v in enumerate(row):
            cells[i].text=str(v)
            if len(t.rows)%2==1: shade(cells[i], "F8FAFC")
    for row in t.rows:
        for i,c in enumerate(row.cells):
            set_cell_margins(c); c.vertical_alignment=WD_CELL_VERTICAL_ALIGNMENT.CENTER
            if widths: c.width=Inches(widths[i])
            for p in c.paragraphs:
                p.paragraph_format.space_after=Pt(1.5); p.paragraph_format.line_spacing=1.05
                for r in p.runs:
                    r.font.name="Arial Unicode MS"; r._element.rPr.rFonts.set(qn("w:eastAsia"),"Arial Unicode MS"); r.font.size=Pt(font)
    return t


