test('从库存异常确认策略，可切换历史参数版本并同步补货计划', async ({ page }) => {
  await page.goto('/inventory')
  await expect(page).toHaveURL(/\/inventory\/overview$/)
  const overviewUrl = page.url()
  const forecast = page.getByRole('region', { name: '库存预测', exact: true })
  const editor = page.getByRole('region', { name: '库存策略调整' })
  const preview = editor.getByRole('region', { name: '参数预览' })
  const versions = editor.getByRole('combobox', { name: '参数版本' })
  const confirm = editor.getByRole('button', { name: '确认', exact: true })
  const waterLevel = forecast.getByRole('region', { name: '当前库存水位' })
  const chart = forecast.getByRole('img', { name: '果糖F55 每日可用库存预测' })
  const newVersion = 'INV-POL-202610-FG-F55-V2'

  async function showOctoberSixteenth() {
    await expect(chart).toBeVisible()
    const bounds = await chart.boundingBox()
    expect(bounds).not.toBeNull()
    // 10 月 16 日是横轴从 9 月 29 日开始的第 18 个刻度。
    const x = 64 + ((bounds!.width - 64 - 20) * 17) / 24
    await chart.hover({ position: { x, y: 100 } })
    await expect(chart.getByText('2026-10-16', { exact: true })).toBeVisible()
  }

  await page.getByRole('button', { name: '评估并调整策略' }).click()
  await expect(page).toHaveURL(overviewUrl)
  await expect(editor.getByRole('heading', { name: '库存策略调整' })).toBeFocused()
  const reason = editor.getByRole('textbox', { name: '调整原因' })
  await expect(reason).toHaveValue(/生产补充周期延长/)
  await expect(editor.locator('form button')).toHaveText(['确认'])
  await expect(versions).toHaveValue('STGY-V1.2')
  await editor.getByText('高级设置', { exact: true }).click()
  await editor.getByRole('spinbutton', { name: '服务水平（%）' }).fill('99')
  await expect(preview.getByText('188.57 吨', { exact: true })).toBeVisible()
  await expect(waterLevel.getByText('166.48 吨', { exact: true })).toBeVisible()
  await expect(forecast.getByText('策略 STGY-V1.2', { exact: true })).toBeVisible()
  await showOctoberSixteenth()
  await expect(chart.getByText('安全库存', { exact: true })).toBeVisible()
  await expect(chart.getByText('补货点', { exact: true })).toBeVisible()
  for (const amount of ['0 吨', '564.23 吨', '166.48 吨', '998.48 吨']) {
    await expect(chart.getByText(amount, { exact: true })).toBeVisible()
  }

  await confirm.click()
  await expect(versions).toHaveValue(newVersion)
  await expect(waterLevel.getByText('188.57 吨', { exact: true })).toBeVisible()
  await expect(forecast.getByText(`策略 ${newVersion}`, { exact: true })).toBeVisible()
  await showOctoberSixteenth()
  for (const amount of ['0 吨', '589.75 吨', '188.57 吨', '1,020.57 吨']) {
    await expect(chart.getByText(amount, { exact: true })).toBeVisible()
  }

  await versions.selectOption('STGY-V1.2')
  await expect(preview.getByText('166.48 吨', { exact: true })).toBeVisible()
  await expect(waterLevel.getByText('188.57 吨', { exact: true })).toBeVisible()
  await confirm.click()
  await expect(waterLevel.getByText('166.48 吨', { exact: true })).toBeVisible()
  await versions.selectOption(newVersion)
  await confirm.click()
  await page.reload()
  await expect(versions).toHaveValue(newVersion)
  await expect(versions.getByRole('option')).toHaveCount(2)
  await expect(waterLevel.getByText('188.57 吨', { exact: true })).toBeVisible()
  await expect(page).toHaveURL(overviewUrl)
  await editor.getByRole('link', { name: '查看补货计划明细' }).click()
  await expect(page.getByRole('heading', { name: '补货计划明细', exact: true })).toBeVisible()
  await expect(page.getByText(new RegExp(newVersion))).toBeVisible()
})

