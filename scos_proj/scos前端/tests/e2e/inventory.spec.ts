test('月度确认量约束周计划，生产确认后按可销售日期计入库存', async ({ page }) => {
  await page.goto('/inventory')
  await page.getByRole('menuitem', { name: '补货计划明细' }).click()
  await page.getByRole('link', { name: '月度计划', exact: true }).click()
  const monthly = page.getByRole('region', { name: '月度生产补充基准' })
  const monthlyAmount = monthly.getByRole('spinbutton', { name: '月度确认量（吨）' })
  await monthlyAmount.fill('3349')
  await monthlyAmount.press('Tab')
  await monthly.getByRole('button', { name: '确认月度计划' }).click()
  await expect(
    monthly.getByText('已确认月度生产补充额度，周度计划将使用更新后的剩余额度。'),
  ).toBeVisible()
  await page.getByRole('link', { name: '周度计划', exact: true }).click()
  await expect(page.getByText('月度剩余额度 50 吨', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '查看第 3 周' }).click()
  const detail = page.getByRole('region', { name: '第 3 周日度明细' })
  const firstBatch = detail.getByRole('row').filter({ hasText: /^2026-10-13/ })
  await firstBatch.getByRole('button', { name: '调整补充量' }).click()
  const dialog = page.getByRole('dialog', { name: '调整 2026-10-13 补充量' })
  const amount = dialog.getByRole('spinbutton', { name: '试算补充量（吨）' })
  await amount.fill('50')
  await amount.press('Tab')
  await dialog.getByRole('button', { name: '应用试算' }).click()
  const confirmation = page.getByRole('region', { name: '第 3 周生产确认' })
  const batch = confirmation.getByRole('row').filter({ hasText: '2026-10-13' })
  await expect(batch.getByRole('cell', { name: '2026-10-16', exact: true })).toBeVisible()
  await confirmation.getByRole('button', { name: '提交生产确认' }).click()
  await expect(batch.getByText('待生产确认', { exact: true })).toBeVisible()
  await confirmation.getByRole('button', { name: '模拟生产确认' }).click()
  await expect(batch.getByText('已确认', { exact: true })).toBeVisible()
  await expect(firstBatch.getByRole('button', { name: '调整补充量' })).toHaveCount(0)
  await expect(page.getByText('月度剩余额度 0 吨', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: '日度监控', exact: true }).click()
  await page.reload()
  const daily = page.getByRole('region', { name: '28 天库存滚动监控', exact: true })
  await expect(daily.getByRole('columnheader', { name: '入库量', exact: true })).toBeVisible()
  const receiptsColumn = (await daily.getByRole('columnheader').allTextContents()).findIndex(
    (name) => /入库量/.test(name),
  )
  expect(receiptsColumn).toBeGreaterThanOrEqual(0)
  const receiptDate = daily.getByRole('row').filter({ hasText: /^2026-10-16/ })
  await expect(receiptDate.getByRole('cell').nth(receiptsColumn)).toHaveText('50 计划入库')
})
