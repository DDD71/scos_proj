test('切换安全库存设置方式并预览补货阈值，确认后更新预测', async ({ page }) => {
  await page.goto('/inventory')
  const editor = page.getByRole('region', { name: '库存策略调整' })
  const preview = editor.getByRole('region', { name: '参数预览' })
  const dynamic = editor.getByRole('radio', { name: '按服务水平计算' })
  const fixed = editor.getByRole('radio', { name: '直接填写吨数' })
  const serviceLevel = editor.getByRole('spinbutton', { name: '服务水平（%）' })
  const fixedSafetyStock = editor.getByRole('spinbutton', { name: '安全库存（吨）', exact: true })
  const advanced = editor.getByText('高级设置', { exact: true })
  const forecast = page.getByRole('region', { name: '库存预测', exact: true })
  const week = forecast.getByRole('button', { name: /第\s*3\s*周/ })
  await expect(dynamic).toBeChecked()
  await expect(preview).toContainText('166.48 吨')
  await expect(serviceLevel).toBeHidden()
  await advanced.click()
  await expect(serviceLevel).toHaveValue('98')
  await serviceLevel.fill('99')
  await expect(preview).toContainText('188.57 吨')

  await fixed.check()
  await expect(fixedSafetyStock).toHaveValue('188.57')
  await fixedSafetyStock.fill('170')
  for (const quantity of ['170 吨', '1,370 吨', '1,770 吨']) {
    await expect(preview.getByText(quantity, { exact: true })).toBeVisible()
  }
  await expect(week.getByText('166.48 吨', { exact: true })).toBeVisible()
  await editor.getByRole('button', { name: '确认', exact: true }).click()
  await expect(week.getByText('170 吨', { exact: true })).toBeVisible()

  await dynamic.check()
  await advanced.click()
  await expect(serviceLevel).toHaveValue('99')
  await expect(preview).toContainText('188.57 吨')
  await expect(week.getByText('170 吨', { exact: true })).toBeVisible()
  await fixed.check()
  await expect(fixedSafetyStock).toHaveValue('170')
})

