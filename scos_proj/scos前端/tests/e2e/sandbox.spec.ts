test('生产能力下降默认参数可直接推演，展示减产影响并能恢复默认', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/sandbox')
  await page.getByRole('button', { name: /生产能力下降/ }).click()
  const start = page.getByLabel('哪天开始减产')
  const percentage = page.getByLabel('减产比例（%）')
  const duration = page.getByLabel('减产持续几天')
  await expect(start).toHaveValue('2026-09-30')
  await expect(percentage).toHaveValue('30')
  await expect(duration).toHaveValue('3')
  await page.getByRole('button', { name: '开始推演' }).click()
  const results = page.getByRole('region', { name: '推演结果' })
  await expect(results).toBeVisible()
  await results.getByText('查看关键指标对比', { exact: true }).click()
  await expect(results.getByText('时段内计划产量缺口')).toBeVisible()
  await page.getByText('保存、导出与评估', { exact: true }).click()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出报告' }).click()
  const report = JSON.parse(await readFile(await (await download).path(), 'utf8')) as {
    推演结果: SandboxRun
  }
  const run = report.推演结果
  const lost = run.metrics.find(({ key }) => key === 'lost-output')!
  const closing = run.metrics.find(({ key }) => key === 'closing')!
  expect(lost.simulated).toBeGreaterThan(0)
  expect(closing.simulated).toBeCloseTo(closing.base! - lost.simulated!, 3)
  await results.screenshot({ path: testInfo.outputPath('sandbox-production-default.png') })
  await percentage.fill('0')
  await page.getByRole('button', { name: '重新推演' }).click()
  await results.getByText('查看关键指标对比', { exact: true }).click()
  await expect(
    results
      .getByRole('row', { name: /时段内计划产量缺口/ })
      .getByRole('cell')
      .nth(1),
  ).toHaveText('0 吨')
  await page.getByRole('button', { name: '恢复默认' }).click()
  await expect(start).toHaveValue('2026-09-30')
  await expect(percentage).toHaveValue('30')
  await expect(duration).toHaveValue('3')
  expect(errors).toEqual([])
})

