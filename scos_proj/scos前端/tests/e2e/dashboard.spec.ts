import { expect, test } from '@playwright/test'

test('驾驶舱显示总览，期间、指标溯源及地图交互可操作', async ({ page }) => {
  await page.goto('/dashboard')
  await expect(page.getByRole('heading', { name: '供应链驾驶舱', exact: true })).toBeVisible()
  const metrics = page.getByRole('region', { name: '全局核心指标' })
  await expect(metrics.getByRole('button')).toHaveCount(5)
  await expect(metrics).toContainText('96.4%')
  const customerChart = page.getByRole('img', { name: '重点客户合同履约', exact: true })
  const chartBounds = await customerChart.boundingBox()
  expect(chartBounds).not.toBeNull()
  await customerChart.click({ position: { x: 45 + (chartBounds!.width - 59) / 6, y: 100 } })
  await expect(page.getByRole('button', { name: /图表选中 可口可乐/ })).toBeVisible()
  await expect(page.getByRole('table').getByRole('row')).toHaveCount(2)
  await page.getByRole('button', { name: /图表选中 可口可乐/ }).click()

  await page.getByLabel('统计期间').selectOption('2026-08')
  await expect(metrics).toContainText('94.8%')
  await expect(page.getByText('2026-08-31', { exact: true })).toBeVisible()
  await metrics.getByRole('button', { name: /成品库存周转天数/ }).click()
  const metric = page.getByRole('dialog', { name: '指标溯源' })
  await expect(metric).toContainText('统计口径')
  await metric.getByRole('button', { name: '查看库存专题' }).click()
  await expect(page.getByRole('tab', { name: '库存' })).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('heading', { name: '库存月度快照' })).toBeVisible()

  const map = page.getByRole('region', { name: '供应链地图' })
  await map.getByRole('img', { name: '以太仓工厂为中心的供应链线路图' }).hover()
  await page.mouse.wheel(0, -180)
  await expect(map).toContainText('110%')
  await map.getByRole('button', { name: '复位' }).click()
  await expect(map).toContainText('100%')
  await map.getByRole('button', { name: '放大地图' }).click()
  await expect(map).toContainText('125%')
  await map.getByRole('button', { name: '复位' }).click()
  await expect(map).toContainText('100%')
  await map.getByLabel('地图线路').selectOption('outbound')
  await map.getByLabel('查看地图节点').selectOption({ label: '可口可乐' })
  const node = page.getByRole('dialog', { name: '供应链地图详情' })
  await expect(node).toContainText('可口可乐')
  await expect(node).toContainText('1,680 吨')
})

test('采购预警下钻到执行行，延期反馈返回驾驶舱后更新风险', async ({ page }) => {
  await page.goto('/dashboard')
  await page.getByRole('button', { name: /查看全部/ }).click()
  const alerts = page.getByRole('dialog', { name: '供应链预警', exact: true })
  await alerts.getByLabel('业务域').selectOption('procurement')
  await alerts.getByRole('button', { name: /玉米淀粉到货延期.*黑龙江昊天/s }).click()
  const detail = page.getByRole('dialog', { name: '预警详情' })
  await expect(detail).toContainText('400 吨')
  await detail.getByRole('link', { name: /带入沙盘推演/ }).click()
  await expect(page.getByRole('complementary', { name: '驾驶舱基线' })).toContainText(
    '玉米淀粉到货延期',
  )
  await page.goBack()
  await page.getByRole('button', { name: /查看全部/ }).click()
  await alerts.getByLabel('业务域').selectOption('procurement')
  await alerts.getByRole('button', { name: /玉米淀粉到货延期.*黑龙江昊天/s }).click()
  await detail.getByRole('link', { name: /查看要货执行/ }).click()
  await expect(page).toHaveURL(/requisition\/execution.*rowId=REQEXE-003/)
  const execution = page.getByRole('dialog', { name: '要货执行详情' })
  await execution.getByRole('button', { name: '模拟新的延期反馈' }).click()
  await expect(execution).toContainText('290 吨')

  await page.goto('/dashboard')
  await expect(page.getByRole('region', { name: /待处置预警/ })).toContainText('290 吨')
})

test('F55 库存预警打开对应产品补货计划', async ({ page }) => {
  await page.goto('/dashboard')
  await page.getByRole('button', { name: /查看全部/ }).click()
  const alerts = page.getByRole('dialog', { name: '供应链预警', exact: true })
  await alerts.getByLabel('业务域').selectOption('inventory')
  await alerts.getByRole('button', { name: /果糖F55/ }).click()
  const detail = page.getByRole('dialog', { name: '预警详情' })
  await expect(detail).toContainText('安全库存')
  await detail.getByRole('link', { name: /查看成品库存与补货/ }).click()
  await expect(page).toHaveURL(/inventory\/plans\?mode=day&product=FG-F55/)
  await expect(page.getByRole('heading', { name: '补货计划明细', exact: true })).toBeVisible()
})
